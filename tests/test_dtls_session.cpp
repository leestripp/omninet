// OmniNet - DtlsSession tests: pump-driven DTLS handshake + encryption in memory
#include "crypto/Crypto.h"
#include "net/DtlsSession.h"

#include <cstdio>
#include <cstring>
#include <fstream>
#include <string>

using namespace OmniNet;

static int g_failures = 0;

#define ASSERT_TRUE(cond) do { \
    if (!(cond)) { std::printf("FAIL %s:%d: %s\n", __FILE__, __LINE__, #cond); ++g_failures; } \
} while (0)
#define ASSERT_EQ(a, b) ASSERT_TRUE((a) == (b))

namespace {

std::string writeTemp(const std::vector<uint8_t>& pem, const char* name) {
    std::string path = std::string("/tmp/omninet_dtls_session_") + name;
    std::ofstream f(path, std::ios::binary);
    f.write(reinterpret_cast<const char*>(pem.data()), pem.size());
    return path;
}

sockaddr_in fakePeer(uint16_t port) {
    sockaddr_in a{};
    a.sin_family = AF_INET;
    a.sin_port = htons(port);
    ::inet_pton(AF_INET, "127.0.0.1", &a.sin_addr);
    return a;
}

// Shuttle datagrams between two sessions until both are established
bool runHandshake(DtlsSession& server, DtlsSession& client, int maxRounds = 50) {
    for (int round = 0; round < maxRounds && !(server.isEstablished() && client.isEstablished()); ++round) {
        client.drive();
        server.drive();

        std::vector<std::vector<uint8_t>> c2s, s2c;
        client.pollOutgoing(c2s);
        server.pollOutgoing(s2c);
        for (const auto& d : c2s) server.inputDatagram(d);
        for (const auto& d : s2c) client.inputDatagram(d);

        client.drive();
        server.drive();

        // second drain: handshake responses generated by the drive above
        c2s.clear(); s2c.clear();
        client.pollOutgoing(c2s);
        server.pollOutgoing(s2c);
        for (const auto& d : c2s) server.inputDatagram(d);
        for (const auto& d : s2c) client.inputDatagram(d);
    }
    return server.isEstablished() && client.isEstablished();
}

void runCase(bool requireCookie) {
    auto [certPem, keyPem] = Crypto::generateSelfSignedCert("dtls-session-test", 1);
    ASSERT_TRUE(!certPem.empty());
    std::string certPath = writeTemp(certPem, requireCookie ? "cert_c.pem" : "cert.pem");
    std::string keyPath = writeTemp(keyPem, requireCookie ? "key_c.pem" : "key.pem");

    DtlsSession server;
    ASSERT_TRUE(server.initServer(certPath, keyPath, requireCookie).has_value());
    server.setPeerAddress(fakePeer(5555));

    DtlsSession client;
    ASSERT_TRUE(client.initClient(false).has_value());

    ASSERT_TRUE(runHandshake(server, client));
    ASSERT_TRUE(server.isEstablished() && client.isEstablished());
    ASSERT_TRUE(!server.cipherName().empty());

    // client -> server encrypted message
    const char* msg = "encrypted position update";
    ASSERT_TRUE(client.encrypt({reinterpret_cast<const uint8_t*>(msg), std::strlen(msg)}).has_value());
    std::vector<std::vector<uint8_t>> wire;
    client.pollOutgoing(wire);
    ASSERT_EQ(wire.size(), 1u);
    for (const auto& d : wire) server.inputDatagram(d);
    std::vector<std::vector<uint8_t>> plain;
    server.pollPlaintext(plain);
    ASSERT_EQ(plain.size(), 1u);
    ASSERT_EQ(plain[0].size(), std::strlen(msg));
    ASSERT_TRUE(std::memcmp(plain[0].data(), msg, plain[0].size()) == 0);

    // server -> client reply
    const char* reply = "ack";
    ASSERT_TRUE(server.encrypt({reinterpret_cast<const uint8_t*>(reply), 3}).has_value());
    wire.clear();
    server.pollOutgoing(wire);
    for (const auto& d : wire) client.inputDatagram(d);
    plain.clear();
    client.pollPlaintext(plain);
    ASSERT_EQ(plain.size(), 1u);
    ASSERT_TRUE(std::memcmp(plain[0].data(), reply, 3) == 0);

    // Multi-datagram burst preserves boundaries
    for (int i = 0; i < 3; ++i) {
        std::string m = "msg" + std::to_string(i);
        ASSERT_TRUE(client.encrypt({reinterpret_cast<const uint8_t*>(m.data()), m.size()}).has_value());
    }
    wire.clear();
    client.pollOutgoing(wire);
    ASSERT_EQ(wire.size(), 3u);
    for (const auto& d : wire) server.inputDatagram(d);
    plain.clear();
    server.pollPlaintext(plain);
    ASSERT_EQ(plain.size(), 3u);
    ASSERT_TRUE(std::memcmp(plain[2].data(), "msg2", 4) == 0);
}

} // namespace

int main() {
    runCase(false);
    runCase(true);

    if (g_failures == 0) {
        std::printf("All DtlsSession tests passed\n");
        return 0;
    }
    std::printf("%d test(s) failed\n", g_failures);
    return 1;
}
